"""Regenerate checked-in JetBrains Mono coverage with uv run --with pillow==12.0.0.

No font downloads or Python imaging libraries are required for firmware builds.
"""
from pathlib import Path
import math
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "assets/fonts"


def generate(name, filename, size, chars, weight):
    font = ImageFont.truetype(str(FONTS / filename), size * 4)
    font.set_variation_by_axes([
        weight if axis["name"] == b"Weight" else axis["default"]
        for axis in font.get_variation_axes()
    ])
    data, glyphs = [], []
    for char in chars:
        bounds = font.getbbox(char, anchor="ls")
        left, top = (math.floor(v/4) for v in bounds[:2])
        right, bottom = (math.ceil(v/4) for v in bounds[2:])
        width, height = right-left, bottom-top
        offset = len(data)
        if width and height:
            image = Image.new("L", (width*4, height*4))
            ImageDraw.Draw(image).text((-left*4, -top*4), char, font=font, fill=255, anchor="ls")
            image = image.resize((width,height), Image.Resampling.LANCZOS)
            image = image.point(lambda p: (p+8)//17)
            # FreeType's box can include the whole monospace cell, including
            # empty space around a decimal point. Store actual visible bounds.
            ink = image.getbbox()
            if ink:
                left += ink[0]
                top += ink[1]
                image = image.crop(ink)
                width, height = image.size
            else:
                width = height = 0
            alpha = list(image.getdata()) if ink else []
            if len(alpha)%2: alpha.append(0)
            data.extend((alpha[i]<<4)|alpha[i+1] for i in range(0,len(alpha),2))
        glyphs.append(f"  {{{ord(char)}, {offset}, {width}, {height}, {left}, {top}, {round(font.getlength(char)*16)}}},")
    result = [f"const uint8_t k{name}Coverage[] = {{"]
    result += ["  " + ",".join(str(v) for v in data[i:i+32]) + "," for i in range(0,len(data),32)]
    result += ["};", f"const Glyph k{name}Glyphs[] = {{", *glyphs, "};",
               f"const Font k{name} = {{k{name}Glyphs, k{name}Coverage, {len(glyphs)}}};"]
    print(name, len(data), "bytes")
    return "\n".join(result)


if __name__ == "__main__":
    ascii_chars = ''.join(chr(i) for i in range(32,127))
    parts = ["// Generated by scripts/generate_fonts.py; JetBrains Mono is licensed under assets/fonts/OFL.txt.",
             generate("Primary", "JetBrainsMono.ttf", 144, " $%+,-.0123456789", 500),
             generate("Secondary", "JetBrainsMono.ttf", 22, ascii_chars, 400),
             generate("Small", "JetBrainsMono.ttf", 12, ascii_chars, 400)]
    (ROOT / "src/font_data.inc").write_text("\n\n".join(parts)+"\n",encoding="ascii")
